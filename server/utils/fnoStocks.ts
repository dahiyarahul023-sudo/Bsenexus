/** True if the given NSE symbol (or mapped BSE scrip code) is an F&O stock. */
export function isFnOStock(symbolOrScrip: string): boolean {
  if (!symbolOrScrip) return false;
  const clean = String(symbolOrScrip).trim().toUpperCase();
  if (FNO_SET.has(clean)) return true;
  return Object.values(FNO_BSE_SCRIP).includes(clean);
}
